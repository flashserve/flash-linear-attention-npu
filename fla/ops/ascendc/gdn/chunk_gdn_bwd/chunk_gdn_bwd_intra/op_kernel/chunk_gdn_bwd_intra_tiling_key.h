#ifndef CHUNK_GDN_BWD_INTRA_TILING_KEY_H
#define CHUNK_GDN_BWD_INTRA_TILING_KEY_H

#include "ascendc/host_api/tiling/template_argument.h"

#define CHUNK_GDN_BWD_INTRA_FIXED 0
#define CHUNK_GDN_BWD_INTRA_VARLEN 1
#define CHUNK_GDN_BWD_INTRA_MAIN_BF16 0
#define CHUNK_GDN_BWD_INTRA_MAIN_FP16 1
#define CHUNK_GDN_BWD_INTRA_GATE_BF16 0
#define CHUNK_GDN_BWD_INTRA_GATE_FP32 1
#define CHUNK_GDN_BWD_INTRA_BETA_BF16 0
#define CHUNK_GDN_BWD_INTRA_BETA_FP32 1
// G_KEY=0 是运行时 G 桶（A2 上 G>4 时选择），实际比例从 tiling->groupSize 读取。
#define CHUNK_GDN_BWD_INTRA_G_RUNTIME 0

ASCENDC_TPL_ARGS_DECL(
    ChunkGdnBwdIntra,
    ASCENDC_TPL_UINT_DECL(STRATEGY_KEY, 1, ASCENDC_TPL_UI_LIST,
                          CHUNK_GDN_BWD_INTRA_FIXED, CHUNK_GDN_BWD_INTRA_VARLEN),
    // 位宽 3 可表达 8 个取值，此处只用到 0/1/2/3/4 共 5 个。G>4 一律落到 0
    // （运行时 G 桶），不新增取值；若将来改为按 G 实例化模板，取值数超过 8 时
    // 必须先扩位宽，否则 TPL 编码重叠、分支路由错乱。
    ASCENDC_TPL_UINT_DECL(G_KEY, 3, ASCENDC_TPL_UI_LIST,
                          CHUNK_GDN_BWD_INTRA_G_RUNTIME, 1, 2, 3, 4),
    ASCENDC_TPL_UINT_DECL(MAIN_KEY, 1, ASCENDC_TPL_UI_LIST,
                          CHUNK_GDN_BWD_INTRA_MAIN_BF16, CHUNK_GDN_BWD_INTRA_MAIN_FP16),
    ASCENDC_TPL_UINT_DECL(GATE_KEY, 1, ASCENDC_TPL_UI_LIST,
                          CHUNK_GDN_BWD_INTRA_GATE_BF16, CHUNK_GDN_BWD_INTRA_GATE_FP32),
    ASCENDC_TPL_UINT_DECL(BETA_KEY, 1, ASCENDC_TPL_UI_LIST,
                          CHUNK_GDN_BWD_INTRA_BETA_BF16, CHUNK_GDN_BWD_INTRA_BETA_FP32));

#define CHUNK_GDN_BWD_INTRA_TPL_ENTRY(STRATEGY, G, MAIN, GATE, BETA)                      \
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_UINT_SEL(STRATEGY_KEY, ASCENDC_TPL_UI_LIST, STRATEGY), \
                         ASCENDC_TPL_UINT_SEL(G_KEY, ASCENDC_TPL_UI_LIST, G),                \
                         ASCENDC_TPL_UINT_SEL(MAIN_KEY, ASCENDC_TPL_UI_LIST, MAIN),          \
                         ASCENDC_TPL_UINT_SEL(GATE_KEY, ASCENDC_TPL_UI_LIST, GATE),          \
                         ASCENDC_TPL_UINT_SEL(BETA_KEY, ASCENDC_TPL_UI_LIST, BETA))

#define CHUNK_GDN_BWD_INTRA_TPL_AUX(STRATEGY, G, MAIN)      \
    CHUNK_GDN_BWD_INTRA_TPL_ENTRY(STRATEGY, G, MAIN, 0, 0), \
    CHUNK_GDN_BWD_INTRA_TPL_ENTRY(STRATEGY, G, MAIN, 0, 1), \
    CHUNK_GDN_BWD_INTRA_TPL_ENTRY(STRATEGY, G, MAIN, 1, 0), \
    CHUNK_GDN_BWD_INTRA_TPL_ENTRY(STRATEGY, G, MAIN, 1, 1)

#define CHUNK_GDN_BWD_INTRA_TPL_MAIN(STRATEGY, G)   \
    CHUNK_GDN_BWD_INTRA_TPL_AUX(STRATEGY, G, 0),    \
    CHUNK_GDN_BWD_INTRA_TPL_AUX(STRATEGY, G, 1)

#define CHUNK_GDN_BWD_INTRA_TPL_G(STRATEGY)       \
    CHUNK_GDN_BWD_INTRA_TPL_MAIN(STRATEGY, 0),    \
    CHUNK_GDN_BWD_INTRA_TPL_MAIN(STRATEGY, 1),    \
    CHUNK_GDN_BWD_INTRA_TPL_MAIN(STRATEGY, 2),    \
    CHUNK_GDN_BWD_INTRA_TPL_MAIN(STRATEGY, 3),    \
    CHUNK_GDN_BWD_INTRA_TPL_MAIN(STRATEGY, 4)

ASCENDC_TPL_SEL(
    CHUNK_GDN_BWD_INTRA_TPL_G(CHUNK_GDN_BWD_INTRA_FIXED),
    CHUNK_GDN_BWD_INTRA_TPL_G(CHUNK_GDN_BWD_INTRA_VARLEN));

#undef CHUNK_GDN_BWD_INTRA_TPL_G
#undef CHUNK_GDN_BWD_INTRA_TPL_MAIN
#undef CHUNK_GDN_BWD_INTRA_TPL_AUX
#undef CHUNK_GDN_BWD_INTRA_TPL_ENTRY

#endif // CHUNK_GDN_BWD_INTRA_TILING_KEY_H
